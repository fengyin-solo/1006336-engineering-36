import type { EntryRow } from './types'
import {
  DUTY_STATUSES,
  LEGACY_SHIFT_FILL_BEFORE,
  PENDING_HANDOVER_STATUSES,
  TEAM_NAMES,
  TEAM_ROSTERS,
  handoverCode,
  legacyShiftFor,
  type Shift,
} from './duty-rules'

function dutyRow(
  id: number,
  date: string,
  shift: Shift,
  team: string,
  status: string,
  personOnDuty: string,
  handoverPerson: string,
  items: string,
): EntryRow {
  return {
    id,
    status,
    pending: PENDING_HANDOVER_STATUSES.includes(status),
    abnormal: false,
    交接编号: handoverCode(date, shift),
    值班班组: team,
    值班日期: date,
    班次: shift,
    值班人员: personOnDuty,
    交接事项: items,
    交接人员: handoverPerson,
    交接状态: status,
  }
}

